# Simple Phase 3 Deployment Zip Creator
# Generated: 2026-10-24

$ErrorActionPreference = 'Stop'
$basePath = Split-Path -Parent $MyInvocation.MyCommand.Path
$timestamp = Get-Date -Format 'yyyyMMdd_HHmmss'
$zipName = "phase3_deployment_$timestamp.zip"
$zipPath = Join-Path $basePath $zipName

# File list
$files = @(
    'modules\dbased\list.php',
    'modules\dbased\view.php',
    'modules\dbased\form.php',
    'modules\dbased\action.php',
    'modules\purchase_orders\form.php',
    'modules\purchase_orders\action.php',
    'modules\purchase_orders\view.php',
    'modules\tickets\form.php',
    'modules\tickets\action.php',
    'modules\tickets\print.php',
    'modules\gatepass\action.php'
)

Write-Host "=== Phase 3 Deployment Package Creator ===" -ForegroundColor Cyan
Write-Host ""

# Verify files
Write-Host "Verifying files..." -ForegroundColor Yellow
$totalSize = 0
$allExist = $true

foreach ($file in $files) {
    $fullPath = Join-Path $basePath $file
    if (Test-Path $fullPath) {
        $size = (Get-Item $fullPath).Length
        $totalSize += $size
        Write-Host "  [OK] $file" -ForegroundColor Green
    } else {
        Write-Host "  [MISSING] $file" -ForegroundColor Red
        $allExist = $false
    }
}

if (-not $allExist) {
    Write-Host ""
    Write-Host "ERROR: Some files are missing. Cannot create package." -ForegroundColor Red
    exit 1
}

Write-Host ""
Write-Host "Total size: $([math]::Round($totalSize/1KB, 2)) KB" -ForegroundColor Cyan
Write-Host ""

# Create staging directory
$stagingDir = Join-Path $basePath "temp_deploy_$timestamp"
Write-Host "Creating staging directory..." -ForegroundColor Yellow
New-Item -ItemType Directory -Path $stagingDir -Force | Out-Null

try {
    # Copy files
    Write-Host "Copying files..." -ForegroundColor Yellow
    foreach ($file in $files) {
        $srcPath = Join-Path $basePath $file
        $destPath = Join-Path $stagingDir $file
        $destDir = Split-Path $destPath -Parent

        if (-not (Test-Path $destDir)) {
            New-Item -ItemType Directory -Path $destDir -Force | Out-Null
        }

        Copy-Item $srcPath $destPath
    }

    # Copy deployment checklist
    $checklistSrc = Join-Path $basePath "PHASE3_DEPLOYMENT.md"
    if (Test-Path $checklistSrc) {
        Copy-Item $checklistSrc (Join-Path $stagingDir "PHASE3_DEPLOYMENT.md")
    }

    # Create README
    $readme = @"
# Phase 3 Deployment Package
Generated: $timestamp

## Contents
11 PHP files for Gingersnaps Warehouse Management System Phase 3

## Upload Instructions
1. Extract this zip to a local directory
2. Login to cPanel File Manager
3. Navigate to /public_html/warehouse/
4. Upload the modules folders (drag and drop)
5. Overwrite existing files when prompted
6. Follow PHASE3_DEPLOYMENT.md for testing checklist

## Files Included
- modules/dbased/list.php (coordinator filter fix)
- modules/dbased/view.php
- modules/dbased/form.php
- modules/dbased/action.php
- modules/purchase_orders/form.php
- modules/purchase_orders/action.php
- modules/purchase_orders/view.php
- modules/tickets/form.php
- modules/tickets/action.php
- modules/tickets/print.php (NEW FILE)
- modules/gatepass/action.php (auto-insert dispatching_priority)

## Target Server
- Host: asmrcctvtechnologies.com
- Path: /public_html/warehouse/
- Database: yitrmcft_gingersnaps

## Bug Fixed
File: modules/dbased/list.php line 264
Fixed coordinator dropdown: changed $crd['name'] to $crd['coordinator_name']

## Post-Upload Testing
Refer to PHASE3_DEPLOYMENT.md section "Post-Deployment Testing"

Generated by: create_deployment_zip.ps1
"@

    Set-Content -Path (Join-Path $stagingDir "README.txt") -Value $readme -Encoding UTF8

    # Create zip
    Write-Host "Creating zip archive..." -ForegroundColor Yellow
    Compress-Archive -Path "$stagingDir\*" -DestinationPath $zipPath -Force

    $zipSize = [math]::Round((Get-Item $zipPath).Length/1KB, 2)

    Write-Host ""
    Write-Host "SUCCESS! Deployment package created:" -ForegroundColor Green
    Write-Host ""
    Write-Host "  File: $zipPath" -ForegroundColor White
    Write-Host "  Size: $zipSize KB" -ForegroundColor White
    Write-Host ""
    Write-Host "Next Steps:" -ForegroundColor Cyan
    Write-Host "  1. Extract the zip file" -ForegroundColor White
    Write-Host "  2. Login to cPanel File Manager" -ForegroundColor White
    Write-Host "  3. Navigate to /public_html/warehouse/" -ForegroundColor White
    Write-Host "  4. Upload the modules folders" -ForegroundColor White
    Write-Host "  5. Run tests from PHASE3_DEPLOYMENT.md" -ForegroundColor White
    Write-Host ""

} catch {
    Write-Host ""
    Write-Host "ERROR: $($_.Exception.Message)" -ForegroundColor Red
    exit 1
} finally {
    # Cleanup
    if (Test-Path $stagingDir) {
        Remove-Item $stagingDir -Recurse -Force -ErrorAction SilentlyContinue
    }
}
