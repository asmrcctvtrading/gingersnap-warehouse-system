CREATE TABLE IF NOT EXISTS smart_buys (
  sb_id          INT UNSIGNED    NOT NULL AUTO_INCREMENT,
  grn_id         INT UNSIGNED    NULL,
  grn_item_id    INT UNSIGNED    NULL,
  qc_item_id     INT UNSIGNED    NULL,
  item_id        INT UNSIGNED    NULL,
  sku_code       VARCHAR(100)    NULL,
  item_name      VARCHAR(255)    NULL,
  color          VARCHAR(100)    NULL,
  size           VARCHAR(50)     NULL,
  brand          VARCHAR(100)    NULL,
  qty            INT UNSIGNED    NOT NULL DEFAULT 0,
  condition_code VARCHAR(50)     NOT NULL DEFAULT 'DEFECTIVE',
  source         VARCHAR(30)     NOT NULL DEFAULT 'QC_FAIL',
  status         VARCHAR(30)     NOT NULL DEFAULT 'PENDING',
  sale_price     DECIMAL(10,2)   NULL,
  sold_date      DATE            NULL,
  disposed_date  DATE            NULL,
  notes          TEXT            NULL,
  created_by     INT UNSIGNED    NULL,
  created_at     TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (sb_id),
  UNIQUE KEY uq_sb_grn_item_source (grn_item_id, source)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
